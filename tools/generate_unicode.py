#!/usr/bin/env python3
"""Generate the pinned Unicode normalization and full case-fold tables."""

import argparse
from pathlib import Path
import subprocess
import unicodedata

UNICODE_VERSION = "16.0.0"


def rune_slice(text):
    return "{" + ", ".join(str(ord(char)) for char in text) + "}"


def generate():
    if unicodedata.unidata_version != UNICODE_VERSION:
        raise SystemExit(
            f"requires Unicode {UNICODE_VERSION}; Python provides "
            f"{unicodedata.unidata_version}"
        )
    decompositions = []
    classes = []
    compositions = []
    case_folds = []
    for code in range(0x110000):
        if 0xD800 <= code <= 0xDFFF:
            continue
        char = chr(code)
        if not 0xAC00 <= code < 0xD7A4:
            decomposition = unicodedata.normalize("NFKD", char)
            if decomposition != char:
                decompositions.append((code, decomposition))
        combining = unicodedata.combining(char)
        if combining:
            classes.append((code, combining))
        raw = unicodedata.decomposition(char)
        if raw and not raw.startswith("<"):
            parts = [int(part, 16) for part in raw.split()]
            if len(parts) == 2:
                pair = "".join(chr(part) for part in parts)
                if unicodedata.normalize("NFC", pair) == char:
                    compositions.append(((parts[0] << 21) | parts[1], code))
        folded = char.casefold()
        if folded != char:
            case_folds.append((code, folded))
    lines = [
        "// Code generated by tools/generate_unicode.py; DO NOT EDIT.",
        f"// Unicode database {UNICODE_VERSION}; decimal scalars keep the table readable.",
        "// Source: Python unicodedata and str.casefold; Unicode Character Database.",
        "// https://www.unicode.org/Public/16.0.0/ucd/ ; see UNICODE-LICENSE.txt.",
        "package main",
        "",
        f'const unicodeDataVersion = "{UNICODE_VERSION}"',
        "",
        "var unicodeNFKD = map[rune][]rune{",
    ]
    lines.extend(f"\t{code}: {rune_slice(text)}," for code, text in decompositions)
    lines.extend(["}", "", "var unicodeCombiningClass = map[rune]uint8{"])
    lines.extend(f"\t{code}: {value}," for code, value in classes)
    lines.extend(["}", "", "var unicodeComposition = map[uint64]rune{"])
    lines.extend(f"\t{key}: {value}," for key, value in sorted(compositions))
    lines.extend(["}", "", "var unicodeCaseFold = map[rune][]rune{"])
    lines.extend(f"\t{code}: {rune_slice(text)}," for code, text in case_folds)
    lines.extend(["}", ""])
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "-o", "--output", type=Path,
        default=Path(__file__).resolve().parents[1] / "unicode_tables.go",
        help="generated Go file",
    )
    parser.add_argument(
        "-c", "--check", action="store_true", help="check the output without writing"
    )
    args = parser.parse_args()
    formatted = subprocess.run(
        ["gofmt"], input=generate(), text=True, capture_output=True, check=True
    ).stdout
    if args.check:
        if args.output.read_text() != formatted:
            raise SystemExit("Unicode tables are out of date")
    else:
        args.output.write_text(formatted)


if __name__ == "__main__":
    main()
